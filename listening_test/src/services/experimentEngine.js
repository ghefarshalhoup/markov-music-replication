// Pure experiment rules: no React, no storage. Easy to read and to check.

export const EXPERIENCE_OPTIONS = [
  { value: 'none', label: 'None' },
  { value: 'some', label: 'Some experience' },
  { value: 'trained', label: 'Musically trained' },
];

export const QUESTIONS = {
  liking: { prompt: 'How much do you like this melody?', low: 'Not at all', high: 'Very much' },
  ending: { prompt: 'Does the ending sound finished?', low: 'Cut off', high: 'Clearly finished' },
  attribution: {
    prompt: 'Was this melody written by a person or generated by a computer?',
    options: [{ value: 'person', label: 'A person' }, { value: 'computer', label: 'A computer' }],
  },
};

/** Which screen a session belongs on, from what has been recorded so far. */
export function stageOf(session, answeredCount) {
  if (!session) return 'setup';
  if (session.status === 'abandoned') return 'declined';
  if (session.status === 'completed') return 'complete';
  if (!session.consent_at) return 'welcome';
  if (!session.experience) return 'experience';
  if (!session.soundcheck_at) return 'soundcheck';
  if (answeredCount < session.trial_order.length) return 'trial';
  return 'complete';
}

/** The first position in the stored order that has no saved answer. The order itself never changes. */
export function nextTrialIndex(order, answeredIndices) {
  const done = new Set(answeredIndices);
  for (let i = 0; i < order.length; i += 1) if (!done.has(i)) return i;
  return order.length;
}

/** Server and local copies of a session: every recorded step counts, whichever copy has it. */
export function mergeSession(local, remote) {
  if (!remote) return local;
  if (!local) return { ...remote, pending: [] };
  const pick = (k) => remote[k] ?? local[k] ?? null;
  const status = [remote.status, local.status].includes('completed') ? 'completed'
    : [remote.status, local.status].includes('abandoned') ? 'abandoned' : 'active';
  return {
    ...local,
    ...remote,
    consent_at: pick('consent_at'),
    experience: pick('experience'),
    soundcheck_at: pick('soundcheck_at'),
    completed_at: pick('completed_at'),
    status,
    trial_order: remote.trial_order,       // the server's stored order is the reference
    pending: local.pending || [],
  };
}

export function isAnswered(a) {
  return Number.isInteger(a.liking) && Number.isInteger(a.ending) && Boolean(a.attribution);
}

export function buildTrial(session, index, answers, replays, responseMs) {
  return {
    session_id: session.session_id,
    trial_index: index,
    clip_id: session.trial_order[index],
    liking: answers.liking,
    ending: answers.ending,
    attribution: answers.attribution,
    replays,
    response_ms: Math.max(0, Math.round(responseMs)),
    answered_at: new Date().toISOString(),
    synced: false,
  };
}
